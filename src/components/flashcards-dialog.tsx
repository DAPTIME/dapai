import { useMemo, useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useServerFn } from "@tanstack/react-start";
import { toast } from "sonner";
import { Layers, Loader2, Trash2 } from "lucide-react";

import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import {
  deleteFlashcard,
  generateFlashcards,
  listFlashcards,
  reviewFlashcard,
} from "@/lib/flashcards.functions";
import type { ModelId } from "@/lib/models";

interface Props {
  chatId: string;
  model: ModelId;
  open: boolean;
  onOpenChange: (v: boolean) => void;
}

const GRADES: Array<{ q: 0 | 1 | 2 | 3; label: string }> = [
  { q: 0, label: "Forgot" },
  { q: 1, label: "Hard" },
  { q: 2, label: "Good" },
  { q: 3, label: "Easy" },
];

/**
 * "Turn this chat into flashcards" + a lightweight spaced-repetition review
 * session. Cards are generated by the user's own backend model.
 */
export function FlashcardsDialog({ chatId, model, open, onOpenChange }: Props) {
  const qc = useQueryClient();
  const list = useServerFn(listFlashcards);
  const gen = useServerFn(generateFlashcards);
  const grade = useServerFn(reviewFlashcard);
  const del = useServerFn(deleteFlashcard);

  const [revealed, setRevealed] = useState(false);
  const [index, setIndex] = useState(0);

  const cardsQuery = useQuery({
    queryKey: ["flashcards", chatId],
    queryFn: () => list(),
    enabled: open,
  });

  const cards = useMemo(
    () => (cardsQuery.data ?? []).filter((c) => c.chat_id === chatId),
    [cardsQuery.data, chatId]
  );
  const due = useMemo(
    () => cards.filter((c) => new Date(c.due_at).getTime() <= Date.now()),
    [cards]
  );
  const current = due[Math.min(index, Math.max(0, due.length - 1))];

  const invalidate = () =>
    qc.invalidateQueries({ queryKey: ["flashcards", chatId] });

  const genMut = useMutation({
    mutationFn: () => gen({ data: { chatId, model } }),
    onSuccess: (rows) => {
      toast.success(`Made ${rows.length} flashcard${rows.length === 1 ? "" : "s"}`);
      setIndex(0);
      setRevealed(false);
      invalidate();
    },
    onError: (e) =>
      toast.error(e instanceof Error ? e.message : "Couldn't make flashcards"),
  });

  const gradeMut = useMutation({
    mutationFn: (vars: { id: string; quality: number }) => grade({ data: vars }),
    onSuccess: () => {
      setRevealed(false);
      setIndex(0);
      invalidate();
    },
    onError: (e) => toast.error(e instanceof Error ? e.message : "Failed"),
  });

  const delMut = useMutation({
    mutationFn: (id: string) => del({ data: { id } }),
    onSuccess: () => {
      setRevealed(false);
      invalidate();
    },
  });

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-lg">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <Layers className="h-4 w-4" /> Flashcards
          </DialogTitle>
          <DialogDescription>
            Cards made from this chat, scheduled with spaced repetition —
            answers you find easy come back later, ones you forget come back
            soon.
          </DialogDescription>
        </DialogHeader>

        <div className="space-y-4">
          <div className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
            <span>
              {cards.length} card{cards.length === 1 ? "" : "s"} · {due.length}{" "}
              due now
            </span>
            <Button
              size="sm"
              onClick={() => genMut.mutate()}
              disabled={genMut.isPending}
              style={{ background: "var(--gradient-brand)" }}
            >
              {genMut.isPending ? (
                <>
                  <Loader2 className="mr-1 h-4 w-4 animate-spin" /> Making cards…
                </>
              ) : (
                <>Turn this chat into flashcards</>
              )}
            </Button>
          </div>

          {cardsQuery.isLoading && (
            <p className="text-sm text-muted-foreground">Loading…</p>
          )}

          {!cardsQuery.isLoading && cards.length === 0 && (
            <p className="rounded-xl border border-dashed border-border p-4 text-sm text-muted-foreground">
              No cards yet. Hit "Turn this chat into flashcards" and DAP AI will
              build a deck from what you've studied here.
            </p>
          )}

          {cards.length > 0 && due.length === 0 && (
            <p className="rounded-xl border border-border bg-card p-4 text-sm text-muted-foreground">
              All caught up — nothing due right now. Come back later and your
              next review will be waiting.
            </p>
          )}

          {current && (
            <div className="rounded-xl border border-border bg-card p-4">
              <div className="text-xs font-medium text-muted-foreground">
                Question
              </div>
              <p className="mt-1 text-sm text-foreground">{current.front}</p>

              {revealed ? (
                <>
                  <div className="mt-4 text-xs font-medium text-muted-foreground">
                    Answer
                  </div>
                  <p className="mt-1 text-sm text-foreground">{current.back}</p>
                  <div className="mt-4 flex flex-wrap gap-2">
                    {GRADES.map((g) => (
                      <Button
                        key={g.q}
                        size="sm"
                        variant={g.q === 0 ? "destructive" : "outline"}
                        disabled={gradeMut.isPending}
                        onClick={() =>
                          gradeMut.mutate({ id: current.id, quality: g.q })
                        }
                      >
                        {g.label}
                      </Button>
                    ))}
                  </div>
                </>
              ) : (
                <Button
                  className="mt-4"
                  size="sm"
                  variant="outline"
                  onClick={() => setRevealed(true)}
                >
                  Show answer
                </Button>
              )}

              <div className="mt-4 flex items-center justify-between text-[11px] text-muted-foreground">
                <span>
                  Reviewed {current.reps}× · interval {current.interval_days}d
                </span>
                <button
                  type="button"
                  className="inline-flex items-center gap-1 hover:text-destructive"
                  onClick={() => delMut.mutate(current.id)}
                >
                  <Trash2 className="h-3 w-3" /> Delete card
                </button>
              </div>
            </div>
          )}
        </div>
      </DialogContent>
    </Dialog>
  );
}
