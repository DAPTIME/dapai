import { createFileRoute, Link } from "@tanstack/react-router";
import { toast } from "sonner";

import { useSiteConfig } from "@/lib/site-config";
import { GAME_FLAGS } from "@/lib/feature-guard";

export const Route = createFileRoute("/games/")({
  head: () => ({
    meta: [
      { title: "DAP Arcade — 8 free games in your browser" },
      {
        name: "description",
        content:
          "Play seven free games right in your browser: 2048, Snake, Spacewar, DAP Track 3D time trials, River Crosser, Flappy and Brick Breaker.",
      },
      { property: "og:title", content: "DAP Arcade — 8 free games in your browser" },
      {
        property: "og:description",
        content:
          "Eight free browser games generated by DAP AI — no download, works on desktop and mobile.",
      },
      { property: "og:type", content: "website" },
      { property: "og:url", content: "https://dapai.lovable.app/games" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: GamesHome,
});

const GAMES = [
  { to: "/games/2048" as const, label: "2048", emoji: "🟨", desc: "Slide, merge, chase 2048." },
  { to: "/games/snake" as const, label: "Snake", emoji: "🐍", desc: "Classic — don't bite yourself." },
  { to: "/games/spacewar" as const, label: "Spacewar", emoji: "🚀", desc: "Dodge asteroids, blast rocks." },
  { to: "/games/daptrack" as const, label: "DAP Track", emoji: "🏎️", desc: "3D low-poly time trials — checkpoints, ghosts, medals, editor." },
  { to: "/games/river" as const, label: "River Crosser", emoji: "🐸", desc: "Hop cars and logs — don't drown." },
  { to: "/games/flappy" as const, label: "Flappy", emoji: "🐤", desc: "Tap to flap between pipes." },
  { to: "/games/breakout" as const, label: "Brick Breaker", emoji: "🧱", desc: "Bounce, smash, clear the wall." },
];

function GamesHome() {
  const siteConfig = useSiteConfig();
  return (
    <div className="mx-auto max-w-3xl">
      <h1 className="bg-gradient-to-r from-primary to-fuchsia-400 bg-clip-text text-3xl font-bold text-transparent">
        DAP Arcade
      </h1>
      <p className="mt-2 text-muted-foreground">
        A small library of fun games generated by DAP AI.
      </p>
      <div className="mt-6 grid grid-cols-1 gap-3 sm:grid-cols-2">
        {GAMES.map((g, i) => {
          const off = siteConfig.flags[GAME_FLAGS[g.to]] === false;
          const card = (
            <>
              <div className="text-3xl transition-transform group-hover:scale-110">{g.emoji}</div>
              <div className="mt-3 text-lg font-semibold">
                {g.label}
                {off && (
                  <span className="ml-2 rounded-full border border-border px-2 py-0.5 text-[10px] uppercase tracking-wide text-muted-foreground">
                    Under maintenance
                  </span>
                )}
              </div>
              <div className="text-sm text-muted-foreground">
                {off ? "Under maintenance — the admin has turned this game off for now." : g.desc}
              </div>
            </>
          );
          if (off) {
            return (
              <button
                key={g.to}
                type="button"
                onClick={() =>
                  toast.info(`${g.label} is under maintenance right now.`)
                }
                style={{ animationDelay: `${i * 60}ms` }}
                className="group animate-fade-in cursor-not-allowed rounded-2xl border border-border bg-card/40 p-5 text-left opacity-40 grayscale transition-all"
              >
                {card}
              </button>
            );
          }
          return (
            <Link
              key={g.to}
              to={g.to}
              style={{ animationDelay: `${i * 60}ms` }}
              className="group animate-fade-in rounded-2xl border border-border bg-card p-5 transition-all hover:-translate-y-0.5 hover:border-primary/60 hover:shadow-lg"
            >
              {card}
            </Link>
          );
        })}
      </div>
      <div className="mt-6 grid gap-2 sm:grid-cols-2">
        <Link to="/games/daptrack/browse" className="rounded-xl border border-border bg-card p-4 hover:border-primary">
          <div className="font-semibold">🌐 Community DAP Track Tracks</div>
          <div className="text-sm text-muted-foreground">Play levels built by the community.</div>
        </Link>
        <Link to="/games/daptrack/editor" className="rounded-xl border border-border bg-card p-4 hover:border-primary">
          <div className="font-semibold">✏️ DAP Track Editor</div>
          <div className="text-sm text-muted-foreground">Build, share, and publish your own tracks.</div>
        </Link>
      </div>
    </div>
  );
}
